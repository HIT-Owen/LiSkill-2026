"""Markdown report generation.

The report is what the demo prints and writes to ``out/report.md``: the pipeline
statistics of §3.1, the RQ1 coverage tables of §4.2, the detection scale and
shape of §4.3–§4.4, plus a step-by-step walkthrough of one example skill.  Every
section is marked DEMO because the underlying corpus is synthetic.
"""

from __future__ import annotations

from pathlib import Path
from typing import Dict, List, Optional, Sequence

from .conflict.lst import IntraConflict
from .conflict.scc import WorkflowResult
from .eval.rq import (
    declaration_kind_distribution,
    inter_summary,
    intra_summary,
    rq1_coverage,
    rq1_license_composition,
)
from .schema import SkillLicenseDoc

def demo_banner(skills: int, licenses: int, sentences: int) -> str:
    """Header of the report: what was actually run, at which scale (§3.1)."""
    return (
        "> **DEMO DATA — read this before comparing any figure with the paper.**\n"
        ">\n"
        "> Everything below is produced by `python -m liskill.cli demo`: the pipeline\n"
        f"> runs end to end on a **{skills}-skill synthetic sample** generated by\n"
        f"> `liskill/demo/corpus.py`, on a {licenses}-license reference set and on\n"
        f"> {sentences} annotated sentences. The generator is *calibrated to* the\n"
        "> distributions the paper reports (declaration coverage, standard-license\n"
        "> mix, cross-level pairs), so these figures are sample estimates around\n"
        "> those distributions — with sampling noise, not reproductions of them.\n"
        ">\n"
        "> The paper instead measures LiSkill-825k: 825,784 skills, a 4,996-license\n"
        "> reference set, 28,578 annotated sentences, 1,000 annotated skills and 500\n"
        "> workflows. Every section repeats its demo sample size next to the paper's\n"
        "> figure, so the two scales are never mixed up.\n"
    )

#: Scale of the paper, printed next to each demo figure (§3.1, §3.3.2, §4.2–§4.4).
PAPER_SCALE = {
    "skills": "825,784 skills",
    "coverage": "10.59% valid / 0.15% invalid / 89.25% missing",
    "licenses": "4,996 licenses (708 standard + 4,288 custom)",
    "sentences": "28,578 sentences",
    "workflows": "500 workflows",
    "skills_annotated": "1,000 annotated skills",
    "intra": "5.42% of skills",
    "inter": "7.60% of workflows",
}

#: Table limits, so that every truncated table says what it is truncating.
INTRA_ROWS = 12
INTER_ROWS = 8
INTER_TERMS = 3


def _demo_note(text: str) -> str:
    return f"_Demo sample: {text}_\n"


def _table(headers: Sequence[str], rows: Sequence[Sequence[object]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    for row in rows:
        lines.append("| " + " | ".join(str(cell) for cell in row) + " |")
    return "\n".join(lines)


def render_license_document(doc: SkillLicenseDoc) -> str:
    """Table-6 style rendering of one skill's three-level license document."""
    rows: List[List[object]] = []
    for record in doc.records():
        rows.append(
            [
                record.level,
                ", ".join(record.license_ids) or "—",
                record.licensing_type,
                record.declaration_kind,
                record.status,
                record.resolved_from or "—",
                record.file_path or "—",
                (record.evidence or "")[:70],
            ]
        )
    return _table(
        ["Level", "license_ids", "licensing", "kind", "status", "resolved_from", "file", "evidence"],
        rows,
    )


def render_intra(conflicts: Sequence[IntraConflict], limit: int = INTRA_ROWS) -> str:
    if not conflicts:
        return "_No intra-skill conflict detected._"
    rows = []
    for conflict in conflicts[:limit]:
        rows.append(
            [
                conflict.skill_id,
                f"{conflict.parent_level} ({conflict.parent_license})",
                f"{conflict.child_level} ({conflict.child_license})",
                f"{conflict.term.term_id} {conflict.term.term_name}",
                f"{conflict.term.parent_attitude} vs {conflict.term.child_attitude}",
                conflict.child_path or "—",
            ]
        )
    return _table(["skill_id", "parent", "child", "term", "attitude", "child file"], rows)


def render_inter(
    results: Sequence[WorkflowResult], limit: int = INTER_ROWS, terms: int = INTER_TERMS
) -> str:
    conflicting = [result for result in results if result.is_conflict]
    if not conflicting:
        return "_No inter-skill conflict detected._"
    rows = []
    for result in conflicting[:limit]:
        for conflict in result.conflicts[:terms]:
            rows.append(
                [
                    result.workflow_id,
                    " → ".join(result.skill_ids),
                    conflict.edge,
                    f"{conflict.parent_license} ⊃ {conflict.child_license}",
                    f"{conflict.term.term_id} {conflict.term.term_name}",
                    f"{conflict.term.parent_attitude} vs {conflict.term.child_attitude}",
                ]
            )
    return _table(
        ["workflow", "activation order", "conflict edge", "license pair", "term", "attitude"],
        rows,
    )


def build_report(
    docs: Sequence[SkillLicenseDoc],
    intra: Sequence[IntraConflict],
    inter: Sequence[WorkflowResult],
    collection: Optional[Dict[str, object]] = None,
    term_database: Optional[Dict[str, object]] = None,
    examples: Optional[Sequence[SkillLicenseDoc]] = None,
    understanding: Optional[Dict[str, object]] = None,
) -> str:
    parts: List[str] = []
    parts.append("# LiSkill — demo run\n")
    parts.append(
        demo_banner(
            skills=len(docs),
            licenses=int(term_database.get("licenses", 0)) if term_database else 0,
            sentences=int(understanding.get("annotated", 0)) if understanding else 0,
        )
        + "\n"
    )

    parts.append("## 1. Collection and preprocessing (§3.1)\n")
    parts.append(
        _demo_note(
            "collector smoke run over the bundled per-platform sample payloads; "
            f"the corpus analysed in §2–§4 is the {len(docs)}-skill demo ecosystem "
            f"written to `out/skills/`. Paper: 2,027,275 raw records → "
            f"{PAPER_SCALE['skills']}"
        )
    )
    if collection:
        plat_rows = [
            [item["platform"], item["pages"], item["records"]]
            for item in collection.get("platforms", [])
        ]
        parts.append(_table(["Platform", "Pages", "Records"], plat_rows) + "\n")
        cleaning = collection.get("cleaning") or {}
        parts.append(
            f"- raw records: **{collection.get('raw_records', 0)}**\n"
            f"- after invalid-record filtering: **{cleaning.get('after_invalid_filter', 0)}**\n"
            f"- after SHA-256(name+description) dedup: **{collection.get('unique_records', 0)}** "
            f"(dedup rate {cleaning.get('dedup_rate(%)', 0)}%)\n"
        )
    else:
        parts.append("_Collection skipped in this run._\n")

    parts.append("\n## 2. RQ1 — license declaration coverage (§4.2)\n")
    coverage = rq1_coverage(docs)
    parts.append(
        _demo_note(f"{coverage['total']} skills. Paper: {PAPER_SCALE['coverage']}")
    )
    parts.append(
        _table(
            ["Category", "Count", "Percentage"],
            [
                [row["category"], row["count"], f"{row['percentage']}%"]
                for row in coverage["rows"]
            ],
        )
        + "\n"
    )
    composition = rq1_license_composition(docs)
    parts.append(
        f"Valid declarations: **{composition['declarations']}** "
        f"(the denominator of every row below).\n"
    )
    parts.append(
        _table(
            ["License", "Count", "Share of valid declarations"],
            [
                [row["license"], row["count"], f"{row['percentage']}%"]
                for row in composition["rows"]
            ],
        )
        + "\n"
    )
    parts.append(
        f"- distinct standard licenses in valid declarations: **{composition['standard_distinct']}** "
        f"(paper: 45)\n"
        f"- declarations registered as custom licenses: **{composition['custom_total']}** "
        f"({composition['custom_ratio']}% of valid declarations; paper: 4,288 declarations, 4.90%)\n"
    )

    parts.append("\n### Declaration kinds\n")
    parts.append(
        _table(
            ["declaration_kind", "Count", "Percentage"],
            [
                [row["kind"], row["count"], f"{row['percentage']}%"]
                for row in declaration_kind_distribution(docs)
            ],
        )
        + "\n"
    )

    parts.append("\n## 3. RQ3 — intra-skill cross-level conflicts (§4.4.1)\n")
    intra_stats = intra_summary(intra, docs)
    parts.append(
        _demo_note(
            f"{intra_stats['skills']} skills. Paper: {PAPER_SCALE['skills']} "
            f"annotated down to {PAPER_SCALE['skills_annotated']}, "
            f"{PAPER_SCALE['intra']} conflicting"
        )
    )
    parts.append(
        f"- skills analysed: **{intra_stats['skills']}**\n"
        f"- skills with an LST conflict: **{intra_stats['conflict_skills']}** "
        f"({intra_stats['conflict_skill_rate']}%)\n"
        f"- conflicting (parent, child) license issues: **{intra_stats['conflict_issues']}**\n"
    )
    if intra_stats["top_pairs"]:
        parts.append("\n### Top conflicting license pairs\n")
        parts.append(
            _table(
                ["Parent → Child", "Count", "Percentage"],
                [
                    [row["pair"], row["count"], f"{row['percentage']}%"]
                    for row in intra_stats["top_pairs"]
                ],
            )
            + "\n"
        )
    if intra_stats["top_terms"]:
        parts.append("\n### Top conflicting terms\n")
        parts.append(
            _table(
                ["Term", "Name", "Count", "Percentage"],
                [
                    [
                        row["term_id"],
                        row["term_name"],
                        row["count"],
                        f"{row['percentage']}%",
                    ]
                    for row in intra_stats["top_terms"]
                ],
            )
            + "\n"
        )
    parts.append(
        f"\n### Detected conflicts "
        f"(first {min(INTRA_ROWS, intra_stats['conflict_issues'])} of "
        f"{intra_stats['conflict_issues']} issues)\n"
    )
    parts.append(render_intra(intra) + "\n")

    parts.append("\n## 4. RQ3 — inter-skill composition conflicts (§4.4.2)\n")
    if inter:
        inter_stats = inter_summary(inter)
        parts.append(
            _demo_note(
                f"{inter_stats['workflows']} workflows. Paper: "
                f"{PAPER_SCALE['workflows']}, {PAPER_SCALE['inter']} conflicting"
            )
        )
        parts.append(
            f"- workflows analysed: **{inter_stats['workflows']}** "
            f"(average chain length {inter_stats['avg_chain_length']})\n"
            f"- workflows with a conflict: **{inter_stats['conflict_workflows']}** "
            f"({inter_stats['conflict_workflow_rate']}%)\n"
            f"- conflicting edges: **{inter_stats['conflict_edges']}** of "
            f"{inter_stats['edges']} ({inter_stats['conflict_edge_rate']}%), "
            f"{inter_stats['undetermined_edges']} edge(s) undetermined "
            f"(one side declares no license)\n"
        )
        if inter_stats["top_pairs"]:
            parts.append("\n### License pairs behind the conflicting edges\n")
            parts.append(
                _table(
                    ["License pair", "Count", "Share of conflict terms"],
                    [
                        [row["pair"], row["count"], f"{row['percentage']}%"]
                        for row in inter_stats["top_pairs"]
                    ],
                )
                + "\n"
            )
        parts.append(
            f"\n### Detected conflicts (first {min(INTER_ROWS, inter_stats['conflict_workflows'])} "
            f"of {inter_stats['conflict_workflows']} conflicting workflows, "
            f"first {INTER_TERMS} terms per edge)\n"
        )
        parts.append(render_inter(inter) + "\n")
    else:
        parts.append("_Inter-skill detection skipped in this run._\n")

    if understanding:
        parts.append("\n## 5. License understanding dataset (§3.3.2)\n")
        parts.append(
            _demo_note(
                f"{understanding.get('annotated', 0)} annotated sentences. "
                f"Paper: 167,812 candidates → 82,940 after dedup → "
                f"{PAPER_SCALE['sentences']}"
            )
        )
        parts.append(
            f"- candidate sentences: **{understanding.get('candidate_sentences', 0)}**\n"
            f"- after embedding dedup (threshold 0.95): **{understanding.get('deduped_sentences', 0)}**\n"
            f"- annotated sentences: **{understanding.get('annotated', 0)}**\n"
            f"- train/dev/test split: **{understanding.get('splits', {})}**\n"
        )

    if term_database:
        parts.append("\n## 6. Term database (§3.4.1)\n")
        parts.append(
            _demo_note(
                f"{term_database.get('licenses', 0)} licenses in the bundled "
                f"reference set. Paper: Λ(l) is built for all "
                f"{PAPER_SCALE['licenses']}"
            )
        )
        parts.append(
            f"- licenses with a complete 31-term mapping: **{term_database.get('licenses', 0)}**\n"
            f"- licenses with a catch-all grant (rule D2): **{term_database.get('granted', 0)}**\n"
        )
        samples = term_database.get("samples") or {}
        if samples:
            rows = []
            for license_id, profile in samples.items():
                shown = ", ".join(
                    f"{tid}={att}"
                    for tid, att in sorted(profile.items(), key=lambda kv: int(kv[0][1:]))
                    if att != "CAN" or tid in {"T1", "T2", "T3", "T5"}
                )
                rows.append([license_id, shown])
            parts.append(_table(["License", "non-default term attitudes"], rows) + "\n")

    if examples:
        parts.append("\n## 7. Walkthrough — one skill per declaration shape\n")
        parts.append(
            "_Hand-written examples under `examples/skills/`, kept outside the "
            "statistics of §2–§4; they only show how one skill's three levels are "
            "recorded._\n"
        )
        for doc in examples:
            parts.append(f"\n### `{doc.skill_id}` (status: {doc.status()})\n")
            parts.append(render_license_document(doc) + "\n")

    parts.append(
        "\n---\n"
        f"Every figure above is a demo-sample estimate from the {len(docs)}-skill "
        "synthetic corpus, not a measurement on LiSkill-825k. Reproduce with "
        "`python -m liskill.cli demo`. The real datasets (LiSkill-825k, the "
        "4,996-entry reference set and the 28,578 annotated sentences) are not "
        "redistributed.\n"
    )
    return "\n".join(parts)


def write_report(markdown: str, path: str | Path) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(markdown, encoding="utf-8")
    return path
